all_data = {}
print("네이버 금융 전체 종목 데이터 수집 시작...")

for code, name in stock_portfolio.items():
    try:
        basic_url = f"https://m.stock.naver.com/api/stock/{code}/integration"
        req = urllib.request.Request(basic_url, headers={'User-Agent': 'Mozilla/5.0'})
        res = urllib.request.urlopen(req).read().decode('utf-8')
        data = json.loads(res)

        price = data.get('closePrice', 'N/A')
        compare = data.get('compareToPreviousClosePrice', '0')
        ratio = data.get('fluctuationsRatio', '0')
        market_sum = data.get('marketValue', 'N/A')
        foreign = data.get('foreignRatio', 'N/A')
        
        per, pbr, eps, dividend = 'N/A', 'N/A', 'N/A', 'N/A'

        fin_url = f"https://m.stock.naver.com/front-api/v1/domestic/stock/{code}/finance"
        fin_req = urllib.request.Request(fin_url, headers={'User-Agent': 'Mozilla/5.0'})
        fin_res = urllib.request.urlopen(fin_req).read().decode('utf-8')
        fin_data = json.loads(fin_res)

        if 'result' in fin_data and isinstance(fin_data['result'], list):
            for item in fin_data['result']:
                if item.get('itemName') == 'PER': per = item.get('value', 'N/A')
                if item.get('itemName') == 'PBR': pbr = item.get('value', 'N/A')
                if item.get('itemName') == 'EPS': eps = item.get('value', 'N/A')
                if item.get('itemName') == '배당수익률': dividend = item.get('value', 'N/A')

        all_data[code] = {
            "name": name, "price": price, "compareToPreviousPrice": compare,
            "fluctuationsRatio": ratio, "marketSum": market_sum, "foreignRatio": foreign,
            "per": per, "pbr": pbr, "eps": eps, "dividendYield": dividend
        }
        time.sleep(0.3) # 네이버 차단 방지 딜레이
    except Exception as e:
        print(f"[{name}] 수집 실패: {e}")

with open('naver_data.json', 'w', encoding='utf-8') as f:
    json.dump(all_data, f, ensure_ascii=False, indent=4)

print("모든 종목 데이터 업데이트 완료! naver_data.json 저장됨.")
